  tax_withheld DECIMAL(15,2) NOT NULL DEFAULT 0.00,
  rate_exception_note VARCHAR(255) NULL,
  schedule_tag CHAR(1) NOT NULL DEFAULT 'A',
  reference_no VARCHAR(40) NULL,
